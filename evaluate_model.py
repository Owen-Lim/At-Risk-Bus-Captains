# 4. IDENTIFY THE SELECTED MODEL
# ================================================================

def identify_model():
    if not METRICS_FILE.exists():
        print(
            "\nNOTE: model_metrics.csv was not found. "
            "The prediction column can still be evaluated, but the selected "
            "model name cannot be confirmed."
        )
        return "Selected ML model (name unavailable)"

    metrics = pd.read_csv(METRICS_FILE)

    required = {"model", "roc_auc"}
    if not required.issubset(metrics.columns):
        return "Selected ML model (metrics format unavailable)"

    model_names = [
        "Logistic Regression",
        "Random Forest",
        "Gradient Boosting",
    ]

    model_rows = metrics[metrics["model"].isin(model_names)].copy()

    if model_rows.empty:
        return "Selected ML model (not identified)"

    model_rows["roc_auc"] = pd.to_numeric(
        model_rows["roc_auc"], errors="coerce"
    )
    model_rows = model_rows.dropna(subset=["roc_auc"])

    if model_rows.empty:
        return "Selected ML model (not identified)"

    # atrisk_pipeline.py chooses the model with the highest mean repeated-CV
    # ROC-AUC. This reproduces that selection rule.
    selected = model_rows.sort_values(
        "roc_auc", ascending=False
    ).iloc[0]

    return str(selected["model"])


