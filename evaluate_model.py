# 5. THRESHOLD-BASED METRICS
# ================================================================

def evaluate_threshold(y, probabilities, samples):
    predictions = (probabilities >= THRESHOLD).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y, predictions, labels=[0, 1]
    ).ravel()

    metrics = {
        "accuracy": accuracy_score(y, predictions),
        "precision": precision_score(y, predictions, zero_division=0),
        "recall": recall_score(y, predictions, zero_division=0),
        "f1": f1_score(y, predictions, zero_division=0),
        "balanced_accuracy": balanced_accuracy_score(y, predictions),
    }

    metric_functions = {
        "accuracy": lambda yy, pp: accuracy_score(
            yy, (pp >= THRESHOLD).astype(int)
        ),
        "precision": lambda yy, pp: precision_score(
            yy, (pp >= THRESHOLD).astype(int), zero_division=0
        ),
        "recall": lambda yy, pp: recall_score(
            yy, (pp >= THRESHOLD).astype(int), zero_division=0
        ),
        "f1": lambda yy, pp: f1_score(
            yy, (pp >= THRESHOLD).astype(int), zero_division=0
        ),
        "balanced_accuracy": lambda yy, pp: balanced_accuracy_score(
            yy, (pp >= THRESHOLD).astype(int)
        ),
    }

    intervals = {
        name: bootstrap_metric_ci(y, probabilities, function, samples)
        for name, function in metric_functions.items()
    }

    majority_accuracy = float(np.mean(y == 0))

    print("\n" + "=" * 72)
    print(f"THRESHOLD METRICS (REFERENCE ONLY: {THRESHOLD:.2f})")
    print("=" * 72)
    print(
        "The 0.50 cutoff is a reference point, not a recommended operating "
        "threshold. Class-weighted model probabilities may not be calibrated."
    )

    for name, value in metrics.items():
        low, high = intervals[name]
        print(
            f"{name.replace('_', ' ').title():<22}: "
            f"{value:.3f}  (95% CI {low:.3f} - {high:.3f})"
        )

    print("\nCONFUSION MATRIX")
    print("-" * 72)
    print(f"True positives  (TP): {tp}")
    print(f"False positives (FP): {fp}")
    print(f"False negatives (FN): {fn}")
    print(f"True negatives  (TN): {tn}")

    print("\nACCURACY BASELINE")
    print("-" * 72)
    print(f"Model accuracy                 : {metrics['accuracy']:.2%}")
    print(f"Always predict no accident     : {majority_accuracy:.2%}")

    if metrics["accuracy"] <= majority_accuracy:
        print("WARNING: Model accuracy does not beat the majority-class baseline.")

    if predictions.sum() == 0:
        print("WARNING: No drivers were flagged at this threshold.")

    result = dict(metrics)

    for name, (low, high) in intervals.items():
        result[f"{name}_ci_low"] = low
        result[f"{name}_ci_high"] = high

    result.update({
        "threshold": THRESHOLD,
        "flagged_drivers": int(predictions.sum()),
        "true_positives": int(tp),
        "false_positives": int(fp),
        "false_negatives": int(fn),
        "true_negatives": int(tn),
        "majority_accuracy": majority_accuracy,
    })

    return result


# ================================================================
# 6. THRESHOLD-FREE RANKING METRICS
# ================================================================

def evaluate_ranking(y, probabilities, samples):
    roc_auc = roc_auc_score(y, probabilities)
    pr_auc = average_precision_score(y, probabilities)

    roc_ci = bootstrap_metric_ci(
        y, probabilities, roc_auc_score, samples
    )
    pr_ci = bootstrap_metric_ci(
        y, probabilities, average_precision_score, samples
    )

    print("\n" + "=" * 72)
    print("THRESHOLD-FREE MODEL RANKING PERFORMANCE")
    print("=" * 72)
    print(
        f"ROC-AUC : {roc_auc:.3f} "
        f"(95% CI {roc_ci[0]:.3f} - {roc_ci[1]:.3f})"
    )
    print(
        f"PR-AUC  : {pr_auc:.3f} "
        f"(95% CI {pr_ci[0]:.3f} - {pr_ci[1]:.3f})"
    )
    print(f"Random-ranking PR-AUC baseline: {y.mean():.3f}")

    return {
        "roc_auc": roc_auc,
        "roc_auc_ci_low": roc_ci[0],
        "roc_auc_ci_high": roc_ci[1],
        "pr_auc": pr_auc,
        "pr_auc_ci_low": pr_ci[0],
        "pr_auc_ci_high": pr_ci[1],
        "random_pr_auc_baseline": float(y.mean()),
    }


# ================================================================
# 7. TOP-X% RISK RANKING
# ================================================================

def evaluate_top_percentages(y, probabilities, samples):
    print("\n" + "=" * 72)
    print("TOP-X% RISK RANKING PERFORMANCE")
    print("=" * 72)
    print("This shows how many accident drivers appear among the highest-risk scores.")

    rows = []
    n = len(y)
    total_accidents = int(y.sum())

    header = (
        f"{'Group':<10}{'Flagged':<10}{'Accidents caught':<19}"
        f"{'Precision':<13}{'Recall':<12}{'Lift':<9}{'Lift 95% CI'}"
    )
    print("\n" + header)
    print("-" * len(header))

    for fraction in TOP_PERCENTAGES:
        selected = top_fraction_indices(probabilities, fraction)
        flagged = len(selected)
        caught = int(y[selected].sum())

        precision = caught / flagged
        recall = caught / max(1, total_accidents)
        lift = precision / y.mean()

        precision_ci = bootstrap_metric_ci(
            y,
            probabilities,
            lambda yy, ss, f=fraction: top_fraction_precision(yy, ss, f),
            samples,
        )
        recall_ci = bootstrap_metric_ci(
            y,
            probabilities,
            lambda yy, ss, f=fraction: top_fraction_recall(yy, ss, f),
            samples,
        )
        lift_ci = bootstrap_metric_ci(
            y,
            probabilities,
            lambda yy, ss, f=fraction: top_fraction_lift(yy, ss, f),
            samples,
        )

        print(
            f"Top {fraction:<6.0%}"
            f"{flagged:<10}"
            f"{str(caught) + '/' + str(total_accidents):<19}"
            f"{precision:<13.2%}"
            f"{recall:<12.2%}"
            f"{lift:<9.2f}"
            f"{lift_ci[0]:.2f} - {lift_ci[1]:.2f}"
        )

        rows.append({
            "top_percentage": fraction,
            "drivers_flagged": flagged,
            "accidents_caught": caught,
            "total_accidents": total_accidents,
            "precision": precision,
            "precision_ci_low": precision_ci[0],
            "precision_ci_high": precision_ci[1],
            "recall": recall,
            "recall_ci_low": recall_ci[0],
            "recall_ci_high": recall_ci[1],
            "lift": lift,
            "lift_ci_low": lift_ci[0],
            "lift_ci_high": lift_ci[1],
        })

    print(
        "\nInterpretation: lift above 1 means the selected group has a higher "
        "accident rate than the overall group. A confidence interval that "
        "includes 1 does not establish a clear improvement over random selection."
    )

    return rows


