"""
EVALUATE BUS CAPTAIN RISK MODEL
===============================

Works with the outputs generated by atrisk_pipeline.py.

Required:
    outputs/driver_risk_scores.csv
    outputs/model_metrics.csv

The pipeline stores out-of-fold ML predictions in driver_risk_scores.csv.
This script evaluates those predictions; it does not fit or test the final
full-data model.

Run:
    python evaluate_model.py

Important:
    The current pipeline configuration uses LABEL_MODE = "all". Since the
    alarm features are from March and accident labels cover January-May,
    these results describe association/ranking, not future accident
    prediction. Use LABEL_MODE = "future" for a temporally valid prediction
    task, then rerun atrisk_pipeline.py before evaluating.
"""

from pathlib import Path
import warnings

import numpy as np
import pandas as pd

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    balanced_accuracy_score,
    roc_auc_score,
    average_precision_score,
    confusion_matrix,
)

warnings.filterwarnings("ignore")


# ================================================================
# 1. CONFIGURATION
# ================================================================

OUT_DIR = Path("outputs")
DATA_FILE = OUT_DIR / "driver_risk_scores.csv"
METRICS_FILE = OUT_DIR / "model_metrics.csv"

THRESHOLD = 0.50  # reference only; not necessarily a calibrated cutoff
TOP_PERCENTAGES = [0.05, 0.10, 0.20, 0.30]
N_BOOTSTRAP = 1000
RANDOM_STATE = 42

# These are available in the supplied atrisk_pipeline.py.
# Do NOT compare against n_accidents: it is derived from the target labels
# and would introduce direct target leakage.
BASELINE_SCORES = {
    "risk_score": "Rule-based risk score",
    "n_alarms": "Total alarms",
    "alarms_per_hour": "Alarms per hour",
}


# ================================================================
# 2. GENERAL HELPERS
# ================================================================

def safe_auc(y, scores):
    """Return ROC-AUC, or NaN if the sample contains only one class."""
    if len(np.unique(y)) < 2:
        return np.nan
    return float(roc_auc_score(y, scores))


def bootstrap_indices(y, n_boot=N_BOOTSTRAP, seed=RANDOM_STATE):
    """Generate bootstrap samples containing both classes."""
    rng = np.random.default_rng(seed)
    n = len(y)
    samples = []

    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        if len(np.unique(y[idx])) == 2:
            samples.append(idx)

    if not samples:
        raise ValueError(
            "Could not generate valid bootstrap samples containing both "
            "accident and non-accident drivers."
        )

    return samples


def percentile_ci(values):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]

    if len(values) == 0:
        return np.nan, np.nan

    low, high = np.percentile(values, [2.5, 97.5])
    return float(low), float(high)


def bootstrap_metric_ci(y, scores, metric_function, samples):
    values = []

    for idx in samples:
        try:
            value = metric_function(y[idx], scores[idx])
            if np.isfinite(value):
                values.append(value)
        except (ValueError, ZeroDivisionError):
            continue

    return percentile_ci(values)


def top_fraction_indices(scores, fraction):
    n = len(scores)
    k = max(1, int(round(n * fraction)))
    return np.argsort(-scores, kind="stable")[:k]


def top_fraction_precision(y, scores, fraction):
    idx = top_fraction_indices(scores, fraction)
    return float(y[idx].mean())


def top_fraction_recall(y, scores, fraction):
    idx = top_fraction_indices(scores, fraction)
    total_positive = int(y.sum())

    if total_positive == 0:
        return np.nan

    return float(y[idx].sum() / total_positive)


def top_fraction_lift(y, scores, fraction):
    baseline_rate = float(y.mean())

    if baseline_rate == 0:
        return np.nan

    return top_fraction_precision(y, scores, fraction) / baseline_rate


# ================================================================
# 3. LOAD PIPELINE OUTPUTS
# ================================================================

def load_data():
    if not DATA_FILE.exists():
        raise FileNotFoundError(
            f"Cannot find {DATA_FILE}. Run atrisk_pipeline.py first."
        )

    df = pd.read_csv(DATA_FILE)

    required = ["Driver", "had_accident", "ml_risk_prob"]
    missing = [column for column in required if column not in df.columns]

    if missing:
        raise ValueError(
            f"Missing required columns in {DATA_FILE}: {missing}"
        )

    for column in ["had_accident", "ml_risk_prob"]:
        df[column] = pd.to_numeric(df[column], errors="coerce")

    original_count = len(df)

    # Keep only rows with a valid target and ML out-of-fold prediction.
    df = df.dropna(subset=["had_accident", "ml_risk_prob"]).copy()

    # Remove invalid target labels and invalid probabilities.
    df = df[df["had_accident"].isin([0, 1])]
    df = df[df["ml_risk_prob"].between(0, 1)]

    df["had_accident"] = df["had_accident"].astype(int)
    df = df.reset_index(drop=True)

    excluded = original_count - len(df)

    if excluded:
        print(
            f"Note: excluded {excluded:,} rows with missing or invalid "
            "labels/predictions."
        )

    if len(df) == 0:
        raise ValueError("No valid evaluation rows found.")

    y = df["had_accident"].to_numpy(dtype=int)
    probabilities = df["ml_risk_prob"].to_numpy(dtype=float)

    if len(np.unique(y)) != 2:
        raise ValueError(
            "Evaluation requires both accident and non-accident drivers."
        )

    print("=" * 72)
    print("BUS CAPTAIN RISK MODEL EVALUATION")
    print("=" * 72)
    print("\nDATA SUMMARY")
    print("-" * 72)
    print(f"Drivers evaluated       : {len(df):,}")
    print(f"Accident drivers        : {int(y.sum()):,}")
    print(f"Non-accident drivers    : {int((y == 0).sum()):,}")
    print(f"Accident rate           : {y.mean():.2%}")
    print(f"Excluded rows           : {excluded:,}")

    print(
        "\nPrediction source: ml_risk_prob from driver_risk_scores.csv "
        "(out-of-fold predictions generated by atrisk_pipeline.py)."
    )

    return df, y, probabilities


