# 9. SAVE REPORTS
# ================================================================

def save_outputs(model_name, ranking, threshold, top_results, comparison):
    OUT_DIR.mkdir(exist_ok=True)

    pd.DataFrame([{
        "model": model_name,
        **ranking,
        **threshold,
    }]).to_csv(OUT_DIR / "model_evaluation_summary.csv", index=False)

    top_df = pd.DataFrame(top_results)
    top_df.insert(0, "model", model_name)
    top_df.to_csv(OUT_DIR / "model_top_risk_evaluation.csv", index=False)

    comparison.to_csv(
        OUT_DIR / "model_baseline_comparison.csv", index=False
    )

    lines = [
        "=" * 72,
        "BUS CAPTAIN RISK MODEL EVALUATION REPORT",
        "=" * 72,
        f"Selected model: {model_name}",
        "",
        "RANKING PERFORMANCE",
        (
            f"ROC-AUC: {ranking['roc_auc']:.3f} "
            f"(95% CI {ranking['roc_auc_ci_low']:.3f}-"
            f"{ranking['roc_auc_ci_high']:.3f})"
        ),
        (
            f"PR-AUC: {ranking['pr_auc']:.3f} "
            f"(95% CI {ranking['pr_auc_ci_low']:.3f}-"
            f"{ranking['pr_auc_ci_high']:.3f})"
        ),
        f"Random-ranking PR-AUC baseline: {ranking['random_pr_auc_baseline']:.3f}",
        "",
        "TOP-X% RISK RANKING",
    ]

    for row in top_results:
        lines.append(
            f"Top {row['top_percentage']:.0%}: "
            f"precision {row['precision']:.2%}, "
            f"recall {row['recall']:.2%}, "
            f"lift {row['lift']:.2f} "
            f"(95% CI {row['lift_ci_low']:.2f}-"
            f"{row['lift_ci_high']:.2f})"
        )

    lines.extend([
        "",
        "THRESHOLD METRICS (REFERENCE ONLY)",
        f"Threshold: {threshold['threshold']:.2f}",
        f"Accuracy: {threshold['accuracy']:.3f}",
        f"Precision: {threshold['precision']:.3f}",
        f"Recall: {threshold['recall']:.3f}",
        f"F1-score: {threshold['f1']:.3f}",
        f"Balanced accuracy: {threshold['balanced_accuracy']:.3f}",
        "",
        "BASELINE COMPARISON",
    ])

    for _, row in comparison.iterrows():
        lines.append(
            f"{row['score']}: ROC-AUC {row['roc_auc']:.3f}, "
            f"PR-AUC {row['pr_auc']:.3f}, "
            f"top-10% precision {row['precision_top10']:.2%}"
        )

    lines.extend([
        "",
        "IMPORTANT LIMITATIONS",
        "1. This script evaluates the out-of-fold ml_risk_prob values saved by the pipeline.",
        "2. These are not predictions from a final model tested on a separate external dataset.",
        "3. The pipeline selects the model using repeated cross-validation and then generates "
        "the saved per-driver predictions using a separate 5-fold cross_val_predict run.",
        "4. The bootstrap confidence intervals resample drivers and do not account for all "
        "model-selection or cross-validation uncertainty.",
        "5. The pipeline's current LABEL_MODE is 'all'. With March alarm features and "
        "January-May accident labels, the task is association/ranking, not future forecasting.",
        "6. Do not use experimental risk scores for employment, disciplinary, or other "
        "high-impact decisions.",
    ])

    report_path = OUT_DIR / "model_evaluation_report.txt"
    report_path.write_text("\n".join(lines), encoding="utf-8")

    print("\n" + "=" * 72)
    print("EVALUATION FILES SAVED")
    print("=" * 72)
    print(OUT_DIR / "model_evaluation_summary.csv")
    print(OUT_DIR / "model_top_risk_evaluation.csv")
    print(OUT_DIR / "model_baseline_comparison.csv")
    print(report_path)


# ================================================================
# 10. MAIN
# ================================================================

def main():
    df, y, probabilities = load_data()
    model_name = identify_model()

    print(f"\nSelected model (from model_metrics.csv): {model_name}")

    samples = bootstrap_indices(y)

    ranking = evaluate_ranking(y, probabilities, samples)
    threshold = evaluate_threshold(y, probabilities, samples)
    top_results = evaluate_top_percentages(y, probabilities, samples)
    comparison = compare_baselines(df, y, probabilities, samples)

    save_outputs(
        model_name,
        ranking,
        threshold,
        top_results,
        comparison,
    )

    print("\nEVALUATION COMPLETED SUCCESSFULLY.")


if __name__ == "__main__":
    main()
