# 8. COMPARE ML WITH SIMPLE BASELINES
# ================================================================

def compare_baselines(df, y, probabilities, samples):
    print("\n" + "=" * 72)
    print("ML MODEL VS SIMPLE BASELINES")
    print("=" * 72)
    print("All scores are evaluated on the same drivers.")

    score_columns = {
        "ML model (out-of-fold)": probabilities,
    }

    for column, label in BASELINE_SCORES.items():
        if column not in df.columns:
            print(f"NOTE: baseline '{column}' not found; skipping.")
            continue

        values = pd.to_numeric(df[column], errors="coerce")
        values = values.replace([np.inf, -np.inf], np.nan)

        # Use the median for missing baseline values. Do not change the
        # evaluation population or compare different sets of drivers.
        if values.notna().sum() == 0:
            print(f"NOTE: baseline '{column}' has no valid values; skipping.")
            continue

        values = values.fillna(values.median())
        score_columns[label] = values.to_numpy(dtype=float)

    ml_auc = roc_auc_score(y, probabilities)
    rows = []

    for label, scores in score_columns.items():
        auc = roc_auc_score(y, scores)
        pr = average_precision_score(y, scores)
        top10 = top_fraction_precision(y, scores, 0.10)

        auc_values = []
        pr_values = []
        gain_values = []

        for idx in samples:
            baseline_auc = safe_auc(y[idx], scores[idx])
            model_auc = safe_auc(y[idx], probabilities[idx])

            if np.isfinite(baseline_auc):
                auc_values.append(baseline_auc)

            if len(np.unique(y[idx])) == 2:
                pr_values.append(average_precision_score(y[idx], scores[idx]))

            if np.isfinite(baseline_auc) and np.isfinite(model_auc):
                gain_values.append(model_auc - baseline_auc)

        auc_ci = percentile_ci(auc_values)
        pr_ci = percentile_ci(pr_values)

        if label == "ML model (out-of-fold)":
            gain = 0.0
            gain_ci = (np.nan, np.nan)
        else:
            gain = ml_auc - auc
            gain_ci = percentile_ci(gain_values)

        rows.append({
            "score": label,
            "roc_auc": auc,
            "roc_auc_ci_low": auc_ci[0],
            "roc_auc_ci_high": auc_ci[1],
            "pr_auc": pr,
            "pr_auc_ci_low": pr_ci[0],
            "pr_auc_ci_high": pr_ci[1],
            "precision_top10": top10,
            "ml_auc_minus_score_auc": gain,
            "auc_gain_ci_low": gain_ci[0],
            "auc_gain_ci_high": gain_ci[1],
        })

    result = pd.DataFrame(rows)

    print(
        f"\n{'Score':<29}{'ROC-AUC':<11}{'95% CI':<19}"
        f"{'PR-AUC':<10}{'Top-10% precision':<20}{'ML AUC gain (95% CI)'}"
    )
    print("-" * 115)

    for _, row in result.iterrows():
        gain_text = (
            "-"
            if not np.isfinite(row["auc_gain_ci_low"])
            else (
                f"{row['ml_auc_minus_score_auc']:+.3f} "
                f"({row['auc_gain_ci_low']:+.3f} to "
                f"{row['auc_gain_ci_high']:+.3f})"
            )
        )

        print(
            f"{row['score']:<29}"
            f"{row['roc_auc']:<11.3f}"
            f"{row['roc_auc_ci_low']:.3f}-{row['roc_auc_ci_high']:.3f}   "
            f"{row['pr_auc']:<10.3f}"
            f"{row['precision_top10']:<20.2%}"
            f"{gain_text}"
        )

    print(
        "\nML AUC gain = ML ROC-AUC minus baseline ROC-AUC. "
        "A positive gain favours ML. If its 95% CI includes zero, "
        "the evidence that ML is better is inconclusive."
    )

    return result


